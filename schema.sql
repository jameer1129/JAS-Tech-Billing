-- =========================================================
-- JAS TECH BILLING — FINAL SUPABASE DATABASE SCHEMA
-- =========================================================
--
-- FINAL DESIGN
--
-- profiles
-- bills
-- bill_items
--
-- Invoice number:
--     YYMMDDNNNN
--
-- Example:
--     2608090000
--     2608090001
--     2608090002
--     260809000A
--     260809000B
--     ...
--     260809FFFF
--
-- NNNN = 4-digit hexadecimal sequence
-- 0000 -> FFFF
-- 65,536 possible invoice numbers per day
--
-- IMPORTANT:
-- The official invoice number is generated ONLY by
-- create_bill().
--
-- The frontend does NOT generate the official number.
--
-- Existing historical invoices are not modified.
-- =========================================================



-- =========================================================
-- 1. PROFILES
-- =========================================================
--
-- One profile per Supabase Auth user.
--
-- role:
--     admin
--     employee
--
-- status:
--     pending
--     approved
--     rejected
-- =========================================================

create table if not exists public.profiles (
  id uuid primary key
    references auth.users(id)
    on delete cascade,

  name text not null default '',

  email text not null default '',

  role text not null default 'employee'
    check (
      role in ('admin', 'employee')
    ),

  status text not null default 'pending'
    check (
      status in ('pending', 'approved', 'rejected')
    ),

  created_at timestamptz not null default now()
);



-- =========================================================
-- 2. BILLS
-- =========================================================
--
-- One row = one saved invoice.
--
-- invoice_no:
--     Official 10-character invoice number and primary key.
--
-- IMPORTANT:
--     invoice_no is generated by create_bill().
--
-- bill_date:
--     Date selected by the user for the invoice.
--
-- The invoice number date and bill_date are intentionally
-- independent.
--
-- Example:
--
-- Current date: 2026-08-09
-- Bill date:    2026-08-07
--
-- Invoice:
--     2608090000
--
-- Bill date:
--     2026-08-07
-- =========================================================

create table if not exists public.bills (

  invoice_no text primary key,

  customer_name text default '',

  customer_phone text default '',

  customer_address text default '',

  bill_date date,

  notes text default '',

  include_notes boolean not null default false,

  show_watermark boolean not null default false,

  show_qr boolean not null default false,

  show_signature boolean not null default false,

  total numeric(12,2) not null default 0
    check (total >= 0),

  created_by uuid
    references public.profiles(id)
    on delete set null,

  created_by_name text default '',

  created_at timestamptz not null default now()
);



-- =========================================================
-- 3. BILL ITEMS
-- =========================================================
--
-- One row = one product/service line inside an invoice.
--
-- No id, item_no, or sort_order is used.
-- Items are linked directly using invoice_no.
-- =========================================================

create table if not exists public.bill_items (

  invoice_no text not null
    references public.bills(invoice_no)
    on delete cascade,

  item_name text not null,

  description text default '',

  serial text default '',

  qty numeric not null default 1
    check (qty > 0),

  price numeric not null default 0
    check (price >= 0),

  amount numeric not null default 0
    check (amount >= 0)
);



-- =========================================================
-- 4. INDEXES
-- =========================================================

create index if not exists
  bill_items_invoice_no_idx
on public.bill_items(invoice_no);


create index if not exists
  bills_invoice_no_idx
on public.bills(invoice_no);


create index if not exists
  bills_customer_name_idx
on public.bills(customer_name);


create index if not exists
  bills_customer_phone_idx
on public.bills(customer_phone);


create index if not exists
  bills_created_at_idx
on public.bills(created_at);



-- =========================================================
-- 5. AUTO-CREATE PROFILE AFTER SIGNUP
-- =========================================================

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin

  insert into public.profiles (
    id,
    name,
    email,
    role,
    status
  )

  values (
    new.id,

    coalesce(
      new.raw_user_meta_data->>'name',
      split_part(new.email, '@', 1)
    ),

    new.email,

    'employee',

    'pending'
  )

  on conflict (id)
  do nothing;

  return new;

end;
$$;



drop trigger if exists
  on_auth_user_created
on auth.users;


create trigger
  on_auth_user_created

after insert
on auth.users

for each row
execute procedure public.handle_new_user();



-- =========================================================
-- 6. ADMIN CHECK FUNCTION
-- =========================================================
--
-- Returns TRUE only when the current user:
--
--     role   = admin
--     status = approved
-- =========================================================

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'admin'
      and status = 'approved'
  );
$$;



-- =========================================================
-- 7. APPROVED USER CHECK
-- =========================================================

create or replace function public.is_approved()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and status = 'approved'
  );
$$;



