-- =========================================================
-- FINAL DATABASE STRUCTURE
-- =========================================================
--
-- profiles
--     ↓
-- users / roles / approval
--
-- bills
--     ↓
-- official invoice records
--
-- bill_items
--     ↓
-- products inside invoices
--
--
-- NO invoice_counters table.
--
--
-- OFFICIAL INVOICE FLOW:
--
-- New Bill
--     ↓
-- User sees "AUTO"
--     ↓
-- Save
--     ↓
-- create_bill()
--     ↓
-- PostgreSQL transaction lock
--     ↓
-- Find today's highest invoice
--     ↓
-- Increment HEX sequence
--     ↓
-- YYMMDDNNNN
--     ↓
-- Insert bill
--     ↓
-- Insert items
--     ↓
-- Return saved bill
--     ↓
-- Frontend receives invoice_no
--     ↓
-- Generate PDF
--
--
-- EXAMPLE:
--
-- First invoice:
--     2608090000
--
-- Second:
--     2608090001
--
-- Tenth:
--     2608090009
--
-- Eleventh:
--     260809000A
--
-- 16th:
--     260809000F
--
-- 17th:
--     2608090010
--
-- 256th:
--     26080900FF
--
-- 257th:
--     2608090100
--
-- Last:
--     260809FFFF
--
-- =========================================================