-- =========================================================
-- 13. CREATE BILL RPC
-- =========================================================
--
-- THIS IS THE IMPORTANT PART.
--
-- The frontend sends:
--
--     customer_name
--     customer_phone
--     customer_address
--     bill_date
--     notes
--     include_notes
--     show_watermark
--     created_by_name
--     items
--
-- The frontend DOES NOT send:
--
--     invoice_no
--     total
--     created_by
--
-- Supabase generates those.
-- =========================================================

create or replace function public.create_bill(

  customer_name text,

  customer_phone text,

  customer_address text,

  bill_date date,

  notes text,

  include_notes boolean,

  show_watermark boolean,

  show_qr boolean,

  show_signature boolean,

  created_by_name text,

  items jsonb

)

returns public.bills

language plpgsql

security definer

set search_path = public

as $$

declare

  new_bill public.bills%rowtype;

  item jsonb;


  -- =======================================================
  -- INVOICE DATE
  --
  -- IMPORTANT:
  -- Invoice number always uses the actual save date.
  --
  -- NOT bill_date.
  -- =======================================================

  v_invoice_date date := current_date;


  last_no text;

  seq integer := -1;

  hex_seq text;

  v_invoice_no text;


  -- =======================================================
  -- TOTAL CALCULATION
  -- =======================================================

  calculated_total numeric(12,2) := 0;

  item_qty numeric;

  item_price numeric;

  item_amount numeric;


begin


  -- =======================================================
  -- 1. AUTHENTICATION
  -- =======================================================

  if auth.uid() is null then

    raise exception
      'Authentication required.';

  end if;



  -- =======================================================
  -- 2. APPROVED USER
  -- =======================================================

  if not public.is_approved() then

    raise exception
      'Not authorized to create bills.';

  end if;



  -- =======================================================
  -- 3. VALIDATE ITEMS
  -- =======================================================

  if items is null

     or jsonb_typeof(items) <> 'array'

     or jsonb_array_length(items) = 0 then

    raise exception
      'At least one invoice item is required.';

  end if;



  -- =======================================================
  -- 4. LOCK INVOICE GENERATION
  --
  -- This prevents two employees from receiving the same
  -- invoice number at the same time.
  --
  -- Example:
  --
  -- Employee A → lock
  -- Employee B → waits
  --
  -- A gets 000A
  -- A saves
  -- A transaction ends
  --
  -- B gets 000B
  -- =======================================================

  perform pg_advisory_xact_lock(

    hashtext(
      to_char(
        v_invoice_date,
        'YYYYMMDD'
      )
    )

  );



  -- =======================================================
  -- 5. FIND LAST INVOICE FOR TODAY
  --
  -- Only new 10-character invoice numbers are considered.
  --
  -- YYMMDD + NNNN
  -- =======================================================

  select b.invoice_no

  into last_no

  from public.bills b

  where b.invoice_no like
        to_char(
          v_invoice_date,
          'YYMMDD'
        ) || '%'

    and char_length(
          b.invoice_no
        ) = 10

    and substring(
          b.invoice_no
          from 7
          for 4
        ) ~ '^[0-9A-Fa-f]{4}$'

  order by b.invoice_no desc

  limit 1;



  -- =======================================================
  -- 6. EXTRACT HEX SEQUENCE
  --
  -- No invoice today:
  --
  --     seq = -1
  --
  --     seq + 1 = 0
  --
  --     0000
  --
  -- Existing:
  --
  --     0000 → 0001
  --     0009 → 000A
  --     000F → 0010
  --     00FF → 0100
  -- =======================================================

  if last_no is not null then

    seq :=

        get_byte(
          decode(
            substring(
              last_no
              from 7
              for 4
            ),
            'hex'
          ),
          0
        ) * 256

      +

        get_byte(
          decode(
            substring(
              last_no
              from 7
              for 4
            ),
            'hex'
          ),
          1
        );

  end if;



  -- =======================================================
  -- 7. DAILY LIMIT
  -- =======================================================

  if seq >= 65535 then

    raise exception
      'Daily invoice limit reached (FFFF).';

  end if;



  -- =======================================================
  -- 8. GENERATE NEXT HEX NUMBER
  -- =======================================================

  hex_seq :=

    upper(

      lpad(

        to_hex(
          seq + 1
        ),

        4,

        '0'

      )

    );



  -- =======================================================
  -- 9. FINAL INVOICE NUMBER
  --
  -- EXACTLY 10 CHARACTERS
  --
  -- YYMMDDNNNN
  -- =======================================================

  v_invoice_no :=

    to_char(
      v_invoice_date,
      'YYMMDD'
    )

    ||

    hex_seq;



  -- =======================================================
  -- 10. CALCULATE TOTAL
  -- =======================================================

  for item in

    select value

    from jsonb_array_elements(items)

  loop


    item_qty :=

      coalesce(
        (item->>'qty')::numeric,
        0
      );


    item_price :=

      coalesce(
        (item->>'price')::numeric,
        0
      );


    if item_qty <= 0 then

      raise exception
        'Item quantity must be greater than zero.';

    end if;


    if item_price < 0 then

      raise exception
        'Item price cannot be negative.';

    end if;


    item_amount :=

      round(
        item_qty * item_price,
        2
      );


    calculated_total :=

      calculated_total
      + item_amount;


  end loop;



  calculated_total :=

    round(
      calculated_total,
      2
    );



  -- =======================================================
  -- 11. CREATE BILL
  --
  -- bill_date remains the date selected by the user.
  --
  -- invoice_no uses current_date.
  -- =======================================================

  insert into public.bills (

    invoice_no,

    customer_name,

    customer_phone,

    customer_address,

    bill_date,

    notes,

    include_notes,

    show_watermark,

    show_qr,

    show_signature,

    total,

    created_by,

    created_by_name

  )

  values (

    v_invoice_no,

    coalesce(
      customer_name,
      ''
    ),

    coalesce(
      customer_phone,
      ''
    ),

    coalesce(
      customer_address,
      ''
    ),

    bill_date,

    coalesce(
      notes,
      ''
    ),

    coalesce(
      include_notes,
      true
    ),

    coalesce(
      show_watermark,
      true
    ),

    coalesce(
      show_qr,
      true
    ),

    coalesce(
      show_signature,
      true
    ),

    calculated_total,

    auth.uid(),

    coalesce(
      created_by_name,
      ''
    )

  )

  returning *

  into new_bill;



  -- =======================================================
  -- 12. INSERT BILL ITEMS
  --
  -- NO sort_order.
  -- =======================================================

  for item in

    select value

    from jsonb_array_elements(items)

  loop


    item_qty :=

      (item->>'qty')::numeric;


    item_price :=

      (item->>'price')::numeric;


    item_amount :=

      round(
        item_qty * item_price,
        2
      );


    insert into public.bill_items (

      invoice_no,

      item_name,

      description,

      serial,

      qty,

      price,

      amount

    )

    values (

      new_bill.invoice_no,

      coalesce(
        item->>'item_name',
        ''
      ),

      coalesce(
        item->>'description',
        ''
      ),

      coalesce(
        item->>'serial',
        ''
      ),

      item_qty,

      item_price,

      item_amount

    );


  end loop;



  -- =======================================================
  -- 13. RETURN CREATED BILL
  -- =======================================================

  return new_bill;


end;

$$;



